export type NavigatorIntent = "specialist" | "reason" | "questions";
export function navigatorReply(
  intent: NavigatorIntent,
  ids: string[],
  locale: Locale,
): string {
  const kk = locale === "kk";
  const selected = learningDocuments.filter((d) => ids.includes(d.id));
  if (!selected.length)
    return kk
      ? "Алдымен оқу құжатын таңдаңыз. Бұл чатта нақты файлдар қабылданбайды."
      : "Сначала выберите учебный документ. Настоящие файлы в этом чате не принимаются.";
  if (intent === "reason")
    return kk
      ? "Төмендегі бағыттар таңдалған оқу құжаттарының нақты үзінділерінен алынған. Диагноздан жаңа бағыт шығарылмайды. Нәтижені растаңыз немесе қабылдамаңыз."
      : "Направления ниже взяты из конкретных цитат выбранных учебных документов. По диагнозу новые направления не определяются. Проверьте результат: его можно подтвердить или отклонить.";
  if (intent === "questions")
    return kk
      ? "Алғашқы кездесудің мақсаты қандай? Ата-ана қатыса ала ма? Сіздің жасыңыздағы баламен және таңдаған тілде жұмыс істей ме? Кездесудің ұзақтығы, құны мен қолжетімділігі қандай? Құжаттағы түсініксіз тұстарды оның авторынан нақтылаңыз."
      : "Какова цель первой встречи? Может ли присутствовать родитель? Работает ли специалист с возрастом вашего ребёнка и на удобном языке? Каковы длительность, стоимость и условия доступности? Неясные места заключения уточните у его автора.";
  if (!selected.some((d) => d.category))
    return kk
      ? "Бұл мысалда маманға нақты бағыт жоқ. Қорытынды авторынан қай маманға және қандай мақсатпен жүгіну керегін нақтылаңыз. Мен бағытты болжай алмаймын."
      : "В этом примере нет явного направления к специалисту. Уточните у автора заключения, к кому и с какой целью обратиться. Я не могу определить это по одному диагнозу.";
  return kk
    ? "Оқу құжаттарында төмендегі мамандар көрсетілген. Бұл жаңа медициналық тағайындау емес. Үзінділерді тексеріп, іздеу үшін әр бағытты бөлек растаңыз. Содан кейін қала, жас және тіл бойынша анкеталарды қарай аласыз."
    : "В учебных документах указаны специалисты ниже. Это извлечение записанной рекомендации. Проверьте цитаты и подтвердите каждое направление отдельно для поиска. Затем можно посмотреть анкеты с учётом города, возраста и языка.";
}
